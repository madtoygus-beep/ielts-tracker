'use strict'
const test=require('node:test'),assert=require('node:assert/strict')
const {readFileSync}=require('node:fs')
const rules=readFileSync('firestore.rules','utf8')
const index=readFileSync('functions/index.js','utf8')
const service=readFileSync('functions/lib/p0bMockWritingReviewService.js','utf8')
const ui=readFileSync('src/pages/TeacherDashboard.jsx','utf8')
test('teacher can no longer directly update Mock submissions in browser',()=>{
  const start=rules.indexOf('match /mockSubmissions/{id} {'),end=rules.indexOf('allow delete:',start)
  assert.ok(start>0&&end>start)
  const block=rules.slice(start,end)
  assert.match(block,/allow update: if adminResultArchiveOnly\(\);/)
  assert.doesNotMatch(block,/teacherMockReviewOnly/)
})
test('UI sends only human review plus immutable attempt locator to trusted callable',()=>{
  assert.match(ui,/const saveMockWritingReviewSecureCall = httpsCallable\(functions, 'saveMockWritingReviewSecure'\)/)
  const start=ui.indexOf('const saveMockWritingReview = async () => {')
  const end=ui.indexOf('const getMockSubmittedCount',start)
  assert.ok(start>=0&&end>start)
  const body=ui.slice(start,end)
  assert.match(body,/review: buildWritingReviewPayload\(\)/)
  assert.doesNotMatch(body,/updateDoc\(/)
  assert.doesNotMatch(body,/setDoc\(/)
  assert.doesNotMatch(body,/\.\.\.result/)
  assert.doesNotMatch(body,/aiEstimatedWritingBand/)
})
test('callable registered and uses trusted current-class membership helper',()=>{
  assert.match(index,/exports\.saveMockWritingReviewSecure = onCall\(request =>/)
  assert.match(index,/createMockWritingReviewService\(\{/)
  assert.match(index,/matchingCurrentMockScoreForStats, schoolIdOf/)
  assert.match(service,/requireCurrentTeacherAcademicStudent\(\{/)
  assert.match(service,/schoolId, tx/)
  assert.doesNotMatch(service,/user\.teacherIds\s*\.includes/)
})
test('server atomically writes Mock result and score with no UI-controlled result',()=>{
  assert.match(service,/return db\.runTransaction\(async tx => \{/)
  assert.match(service,/tx\.update\(current\.ref, \{/)
  assert.match(service,/tx\.update\(selectedScoreRef, scoreGrade\)/)
  assert.match(service,/tx\.create\(canonicalScoreRef, firstScore\)/)
  assert.match(service,/\.\.\.result\.writing/)
  assert.match(service,/\.\.\.result,/)
  assert.match(service,/const \{studentId, mockTestId, submissionId, attemptNumber, submittedAt, review\} = input/)
  assert.doesNotMatch(service,/request\.data\.result|input\.result/)
})
test('AI/provenance copied from original submission and protected when updating existing score',()=>{
  assert.match(service,/aiEstimatedWritingBand: result\.writing\.aiEstimatedBand \?\? null/)
  assert.match(service,/gradedByServer: submission\.gradedByServer === true/)
  assert.match(service,/const scoreGrade = \{/)
  assert.match(service,/scoreMatches\(scoreSnap\.data\(\) \|\| \{\}/)
  assert.match(service,/attemptOf\(submission\) !== attemptNumber/)
})
